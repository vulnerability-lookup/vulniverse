<script setup lang="ts">
import {
  onMounted,
  ref,
} from "vue";

import {
  useRoute,
  useRouter,
} from "vue-router";

import type {
  EditorDocument,
} from "@/editor/contracts";

import {
  recordFromResult,
} from "@/editor/panels/patch2vuln/apply";

import VulniverseEditor from
  "@/editor/VulniverseEditor.ce.vue";

import {
  HttpRepository,
} from "@/repositories/HttpRepository";

import {
  SUPPORTED_PROFILES,
} from "@/editor/profiles";

import {
  BUILTIN_ACTIONS,
} from "@/editor/actions";

import {
  BUILTIN_PANELS,
} from "@/editor/panels";

import {
  filterEnabled,
} from "@/editor/enabled-extensions";

const route = useRoute();
const router = useRouter();

const repository = new HttpRepository("/api/v1");

const enabledActions = ref(BUILTIN_ACTIONS);
const enabledPanels = ref(BUILTIN_PANELS);

onMounted(async () => {
  try {
    const capabilities = await repository.getCapabilities();

    enabledActions.value = filterEnabled(BUILTIN_ACTIONS, capabilities.actions);
    enabledPanels.value = filterEnabled(BUILTIN_PANELS, capabilities.panels);
    repository.setFeatures(capabilities.features);
  } catch (error) {
    console.warn(
      "Could not load app capabilities, showing all built-in panels/actions:",
      error,
    );
  }
});

const selectedProfile = ref<string | null>(null);

// Reviewing a Patch2Vuln candidate (pages/Patch2VulnBatchPage.vue): the
// editor starts from its generated record, and saving links the two.
const candidateId = Number(route.query.candidate) || null;
const initialRecord = ref<EditorDocument | undefined>();
const candidateBatchId = ref<number | null>(null);
const candidateError = ref<string | null>(null);

async function openCandidate(id: number): Promise<void> {
  try {
    const candidate = await repository.getPatch2VulnCandidate(id);

    if (candidate.recordId !== null) {
      await router.replace({ name: "editor", params: { recordId: candidate.recordId } });
      return;
    }

    candidateBatchId.value = candidate.batchId;
    repository.candidateId = id;
    initialRecord.value = recordFromResult(candidate.profile, candidate.result);
    selectedProfile.value = candidate.profile;
  } catch (error) {
    candidateError.value = error instanceof Error ? error.message : "Unable to load the candidate.";
  }
}

if (candidateId !== null) {
  void openCandidate(candidateId);
}

function selectProfile(
  profileId: string,
): void {
  selectedProfile.value = profileId;
}

function handleLoaded(
  identifier: string,
): void {
  router.push({
    name: "editor",
    params: { recordId: identifier },
  });
}

function handleError(
  error: Error,
): void {
  console.error(
    "Editor error:",
    error,
  );
}
</script>

<template>
  <div
    v-if="candidateId !== null && !selectedProfile"
    class="container py-5"
  >
    <div
      v-if="candidateError"
      class="alert alert-danger"
      role="alert"
    >
      {{ candidateError }}
    </div>
    <p
      v-else
      class="text-secondary"
    >
      Loading the generated record…
    </p>
  </div>

  <div
    v-else-if="!selectedProfile"
    class="container py-5"
  >
    <h1 class="h3 mb-4">Create a new vulnerability record</h1>

    <div class="row g-3">
      <div
        v-for="profile in SUPPORTED_PROFILES"
        :key="profile.id"
        class="col-md-6"
      >
        <div class="card h-100">
          <div class="card-body d-flex flex-column">
            <h2 class="h5 card-title">{{ profile.label }}</h2>

            <p class="card-text text-secondary flex-grow-1">
              {{ profile.description }}
            </p>

            <button
              type="button"
              class="btn btn-primary"
              @click="selectProfile(profile.id)"
            >
              Create as {{ profile.label }}
            </button>
          </div>
        </div>
      </div>
    </div>
  </div>

  <div
    v-else
    class="editor-page"
  >
    <p
      v-if="candidateBatchId !== null"
      class="small mb-2"
    >
      Reviewing a record generated by Patch2Vuln. It's only saved when you save it.
      <RouterLink :to="`/patch2vuln/${candidateBatchId}`">Back to the batch</RouterLink>
    </p>

    <div class="editor-card shadow-sm">
      <VulniverseEditor
        :repository="repository"
        mode="create"
        :profile="selectedProfile"
        :initial-record="initialRecord"
        :actions="enabledActions"
        :panels="enabledPanels"
        @loaded="handleLoaded"
        @error="handleError"
      />
    </div>
  </div>
</template>

